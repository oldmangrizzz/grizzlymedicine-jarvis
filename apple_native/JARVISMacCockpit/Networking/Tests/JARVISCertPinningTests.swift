// Unit tests for JARVISCertPinning.swift
// Tests are self-contained: no live network, test fixture certs embedded as DER.
//
// Test matrix:
//   TC-1: Valid pin    — cert SPKI matches stored pin → .success
//   TC-2: Invalid pin  — cert SPKI does NOT match stored pin → .failure(.pinMismatch)
//   TC-3: Wrong host   — host not in pin store → .failure(.hostNotPinned)
//   TC-4: Expired cert — OS trust evaluation rejects (expiry is OS-enforced);
//                        pin logic still extracts and evaluates SPKI correctly.
//                        The full URLSession flow would cancel on OS trust failure
//                        before pin check; the SPKI extraction itself is unaffected
//                        by expiry date — tested via validateCertPin() directly.
//
// All four test fixture certs were generated by:
//   openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 ...
// SPKI pins were extracted by tools/extract_spki_pin.sh.
//
// Swift 5.9+ | macOS 14+ | iOS 17+ | watchOS 10+
// XCTest framework.

